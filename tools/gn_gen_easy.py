"""Gnomad (FORK.md, round CR): Easy's sound set from gnomad-core's content/easy.toml, as the firmware compiles it.

  tools/gn_gen_easy.py SRC OUT.h       (SRC: firmware/gnomad-content: easy.tsv beside pitched.gcpbank, kits.gckbank)

easy.tsv is the core's build of content/easy.toml (tools/author/build_easy.py: picture, slot, sound, kind p/k, bank id,
octave, engine; names resolved against the banks). Nothing here is typed by hand: every row is checked against the
vendored banks (the id's record is authored and carries the row's NAME, the kind is the bank's), so an easy.tsv from
another commit than the banks fails here, not on the synth.

OUT.h (firmware/gnomad-content/gn_easy_set.h, committed; sync-content.sh writes it, tests/gn_content_test.py checks it
byte for byte) declares, for each of easy.toml's pictures, in its order:
  GN_EASY_PIC_<PICTURE>(X)    X(slot, "NAME", BANK_NAME, kind, octave) for each sound: NAME is Easy's (upper case,
                              as the panel shows names), BANK_NAME the bank name's identifier (gn_content.h
                              GN_CONTENT_PN_<BANK_NAME> / KN_<BANK_NAME>), kind P (pitched) or K (kit)
  GN_EASY_PIC_<PICTURE>_COUNT  its sounds
The firmware takes the pictures it shows from here by name (gn_state.c: FUNNY, round CR)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gn_gen_content as gc  # noqa: E402

NAME_MAX = 15                                         # a bank name's longest (SPEC/01: 15 characters)


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: tools/gn_gen_easy.py SRC OUT.h")
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    pitched, kits, lists, _ = gc.census(src)
    byid = {("K" if e == "KITS" else "P", i): n for e, l in lists.items() for i, n, _ in l}
    names = {}
    for (k, i), n in byid.items():
        names.setdefault((k, gc.ident(n)), []).append(i)
    pics, err = {}, []
    for ln, line in enumerate((src / "easy.tsv").read_text().splitlines(), 1):
        if not line.strip():
            continue
        t = line.split("\t")
        if len(t) != 7:
            err.append(f"easy.tsv:{ln}: {len(t)} fields, not 7")
            continue
        pic, slot, sound, kind, bid, octave, _eng = t
        kind = kind.upper()
        if kind not in ("P", "K") or not pic.isalpha():
            err.append(f"easy.tsv:{ln}: kind {kind!r} / picture {pic!r}")
            continue
        got = byid.get((kind, int(bid)))
        if got != sound:
            err.append(f"easy.tsv:{ln}: {sound!r} is bank {kind}{bid}, whose record is {got!r}")
            continue
        if len(names[(kind, gc.ident(sound))]) != 1 or len(sound) > NAME_MAX:
            err.append(f"easy.tsv:{ln}: {sound!r} is not one record's name")
            continue
        rows = pics.setdefault(pic.upper(), [])
        if int(slot) != len(rows):
            err.append(f"easy.tsv:{ln}: slot {slot}, expected {len(rows)}")
        rows.append((sound.upper(), gc.ident(sound), kind, int(octave)))
    if err:
        sys.exit("gn_gen_easy: " + "\n  ".join(err))
    h = ["/* SPDX-License-Identifier: GPL-3.0-only\n"
         " * Generated by tools/gn_gen_easy.py from firmware/gnomad-content/easy.tsv (sync-content.sh): do not edit. */\n",
         "/* Gnomad (FORK.md, round CR): gnomad-core content/easy.toml's pictures, each sound by its bank NAME:\n"
         " * X(slot, \"NAME\", BANK_NAME, kind P/K, octave); gn_state.c binds BANK_NAME through gn_content.h */\n",
         "#pragma once\n"]
    for pic, rows in pics.items():
        h.append(f"\n#define GN_EASY_PIC_{pic}_COUNT {len(rows)}u\n#define GN_EASY_PIC_{pic}(X)")
        for n, (name, ident, kind, octave) in enumerate(rows):
            h.append(f" \\\n    X({n}, \"{name}\", {ident}, {kind}, {octave})")
        h.append("\n")
    out.write_text("".join(h))
    print(f"gn_gen_easy: {out}: " + ", ".join(f"{p} {len(r)}" for p, r in pics.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
