#!/bin/sh
# Gnomad, a fork of Felucca (see FORK.md). Not part of upstream Felucca.
# The fork's host tests (no hardware), from the repo root, after ./build.sh and the package to install
# (.github/ci/released_package.py); the workflow runs them after upstream's tests/run_tests.sh:
#   tests/run_fork_tests.sh NAME PACKAGE_TO_INSTALL.fwsc LOADER_SHA256
# NAME: the build's name (FELUCCA_VERSION, build/gen/gn_name.h), "GNOMAD <milestone> <commit>";
# PACKAGE_TO_INSTALL: this app with upstream's released update loader, whose SHA-256 is LOADER_SHA256.
#
# package       tools/gn_package_check.py reads packages as the device does: genuine ones pass, malformed ones
#               fail (tests/gn_package_test.py); the package to install passes it against build/felucca.fwsc and
#               the pinned loader, and web/fm1pkg.js (the installer page) reads it as tools/fm1_install.py does.
# update        upstream's own update tests on the package to install: firmware/src/ota.c (the M-UPGRADE entry,
#               upstream's as released) stages its loader and commits; firmware/loader/ldr_core.c writes its app
#               area over another app.
# name          the INFO reply ("FELUCCA " + NAME) fits the 24 characters the editor sends; the ABOUT page
#               drawn with NAME passes upstream's layout lint (tests/ui_render.c on every screen and palette, NAME
#               in place of the tests' "TEST"); PNGs of the ABOUT pages in build/gn_name/about/.
# hooks inert   Easy's hooks in upstream's files (FORK.md, touch list) change nothing while Easy is off:
#               upstream's own host tests that reach a hooked function (seq.c keyboard_block, ui_input.c
#               ui_input and ui_leds, ui_draw.c ui_draw, editor.c ED_PROJECT) built with the hooks and the
#               fork's code in (tests/gn_upstream.c), Easy never entered: each passes as without them, and
#               what they write (the UI renders, the 4-track WAVs) is the same bytes as the same test built
#               with FELUCCA_GN=0 (every hook compiled out) and as upstream's own run (build/ui_new).
# Easy          tests/gn_easy_test.c: Easy's state machine through the firmware's own code (tests/gn_host.h),
#               every finding of the 0.9 Easy's review and the two further findings (the white-key table, the pads on
#               the lower row), built with clang -fsanitize=address,undefined (upstream's sources exempt from
#               the undefined-behaviour checks, tests/gn_ubsan_upstream.txt: its DSP shifts negative values).
#               tests/gn_ux_test.c: the UX rounds (FORK.md): Home, the notes pages, the sound browser, SHIFT, the
#               status strip, built as the others and again with the Gnomad engines (GN_ENGINES 1).
#               tests/gn_stack_test.c: the host stack's high-water, Felucca's walk against Easy's.
#               tests/gn_draw_test.c: every Easy screen in every state drawn whole, -fsanitize=undefined
#               (finding 8). tests/gn_sound_test.c: the eight sounds and the drums through the firmware's audio,
#               each speaks at once, each knob a clear change (the thresholds: FORK.md). tests/gn_screen.c:
#               the screens as PNGs (build/gn_screens, and 2x/), each the same bytes as tests/gn_screens.
# banks         Gnomad engines (FORK.md, round FW-CONTENT): tests/gn_content_test.py, the vendored banks as
#               CONTENT-VERSION.txt lists them and gn_content.h regenerated byte for byte; tests/gn_budget_test.py,
#               the CONTENT line against them; tests/gn_bank_test.c, the presets are the banks' (census by the core's
#               validator, NAMES, PRESET's bytes, every authored record and kit bound and sounding, offered or not
#               (round FW-CONTENT-6), every kit's 16 pads, Easy's sounds by bank ID against the
#               engines-off build's table), ASan and UBSan; built a third time (-DGN_BANK_SYNTH, round FW-CONTENT-5)
#               with 200 synthetic FM sounds: at most 127 presets an engine over NAMES, PRESET and the screens.
# pages         Gnomad engines (FORK.md, round EW): tests/gn_wire_test.c, the Advanced pages on the core (ASan, UBSan).
set -e
export AC79_SDK="${AC79_SDK:-$HOME/fw-AC79_AIoT_SDK}"
cd "$(dirname "$0")/.."
[ $# -eq 3 ] || { echo "usage: tests/run_fork_tests.sh NAME PACKAGE_TO_INSTALL.fwsc LOADER_SHA256"; exit 2; }
NAME=$1
PKG=$2
LDR=$3
OUT=build/host-gn
mkdir -p "$OUT"
CC="${CC:-cc} -O1 -Wall -Wno-unused-function"
fail=0
run() { echo "== $1"; n="$1"; shift; if "$@"; then echo "-- $n: ok"; else echo "-- $n: FAILED rc=$?"; fail=1; fi; }
[ -f build/felucca.fwsc ] || { echo "run ./build.sh first"; exit 1; }
[ -f "$PKG" ] || { echo "no package to install: $PKG (.github/ci/released_package.py)"; exit 1; }

run "package check: genuine packages pass, malformed ones fail; the package to install, as the device reads it" \
    python3 tests/gn_package_test.py build/felucca.fwsc "$PKG" "$LDR"

$CC -DOWN_PKG=1 -o "$OUT/ota_test" tests/ota_test.c
run "M-UPGRADE entry (upstream's ota.c) with the package to install: stages the released loader, commits" \
    "$OUT/ota_test" "$PKG"
head -c 200000 build/felucca.bin > "$OUT/old_app.bin"
python3 tools/fm1pkg_make.py "$OUT/old_app.bin" build/loader/ota.bin "$OUT/old.fwsc" >/dev/null
$CC -o "$OUT/ldr_test" tests/ldr_test.c
run "update loader (upstream's ldr_core.c): another app -> the package to install" \
    "$OUT/ldr_test" "$OUT/old.fwsc" "$PKG"

info="FELUCCA $NAME"
run "INFO \"$info\": ${#info} characters; the editor sends at most 24, the installer page needs \"FELUCCA \"" \
    test "${#info}" -le 24
$CC -O1 -w "-DFELUCCA_VERSION=\"$NAME\"" -Ibuild/gen -Ifirmware/src -Itests -o "$OUT/ui_render_name" tests/ui_render.c -lm
rm -rf build/gn_name
mkdir -p build/gn_name/ui_new/ppm build/gn_name/ui_slot
run "the ABOUT page with \"$NAME\": upstream's renders and layout lint (every screen, every palette)" \
    "$OUT/ui_render_name" build/gn_name/ui_new build/gn_name/ui_slot
about() {
    python3 - "$NAME" <<'EOF'
import sys
from pathlib import Path
from PIL import Image
name, src, out = sys.argv[1], Path("build/gn_name/ui_new"), Path("build/gn_name/about")
# bytes: the texts are the firmware's 8-bit strings (0x85 is its ellipsis)
rows = [r.split(b"\t") for r in (src / "text_audit.tsv").read_bytes().split(b"\n") if r.startswith(b"about\t")]
drawn = bool(rows) and len(rows[0]) > 9 and name.encode() in rows[0][9]
print(f"{'the ABOUT page draws ' + repr(name):<78} {'ok' if drawn else 'FAIL'}")
out.mkdir(parents=True, exist_ok=True)
shots = sorted((src / "ppm").glob("*_about*.ppm"))
for f in shots:
    Image.open(f).convert("RGB").save(out / f"{f.stem}.png")
print(f"{len(shots)} renders of the ABOUT pages in {out}")
sys.exit(0 if drawn and shots else 1)
EOF
}
run "the ABOUT page shows the name; its PNGs" about

# Easy's hooks change nothing while Easy is off (tests/gn_upstream.c)
CCU="${CC:-cc} -w -Ibuild/gen -Ifirmware/src -Itests"
upb() {                                    # test, FELUCCA_GN, cc flags: build/host-gn/up<GN>_<test>
    $CCU $3 -DFELUCCA_GN=$2 "-DGN_UPSTREAM_TEST=\"$1.c\"" -o "$OUT/up$2_$1" tests/gn_upstream.c -lm
}
up() {                                     # test, cc flags, its arguments: built with the hooks, run
    t=$1; f=$2; shift 2
    upb "$t" 1 "$f" || return 1
    "$OUT/up1_$t" "$@" > "$OUT/up1_$t.log" 2>&1
    rc=$?
    tail -$([ $rc -eq 0 ] && echo 1 || echo 20) "$OUT/up1_$t.log"
    return $rc
}
run "hooks in: scales (upstream's scale_test)" up scale_test -O2
run "hooks in: chord keys (chord_test)" up chord_test -O1
run "hooks in: motion, chance, songs (motion_test)" up motion_test -O1
run "hooks in: MIDI clock, bend, panic (midi_control_test)" up midi_control_test -O1
run "hooks in: the UI: loads, undo, REC, MIDI IN, saves, grid, song (ui_test)" up ui_test -O1
run "hooks in: audio overload, fades (audio_test)" up audio_test -O1
run "hooks in: persistence (persistence_test)" up persistence_test -O1
run "hooks in: full backup (backup_test)" up backup_test -O1
run "hooks in: the editor protocol (editor_test)" up editor_test -O1
run "hooks in: golden renders, health, voices (regress, tests/golden.txt)" \
    up regress -O2 tests/golden.txt tests/cpu_baseline.txt
same_tree() {                              # two folders: every file the same bytes
    a=$1; b=$2
    [ -d "$a" ] && [ -d "$b" ] || { echo "missing $a or $b"; return 1; }
    diff -rq "$a" "$b" && echo "$(find "$a" -type f | wc -l | tr -d ' ') files, the same bytes"
}
ui_renders() {                             # upstream's UI renders with the hooks, without, upstream's own
    rm -rf build/gn_upstream && mkdir -p build/gn_upstream
    for g in 0 1; do
        upb ui_render $g -O1 || return 1
        mkdir -p build/gn_upstream/ui$g/ppm build/gn_upstream/slot$g
        "$OUT/up${g}_ui_render" build/gn_upstream/ui$g build/gn_upstream/slot$g > "$OUT/up${g}_ui_render.log" 2>&1 ||
            { tail -3 "$OUT/up${g}_ui_render.log"; return 1; }
    done
    tail -1 "$OUT/up1_ui_render.log"
    same_tree build/gn_upstream/ui0/ppm build/gn_upstream/ui1/ppm &&
    cmp build/gn_upstream/ui0/text_audit.tsv build/gn_upstream/ui1/text_audit.tsv &&
    same_tree build/gn_upstream/slot0 build/gn_upstream/slot1 &&
    { [ ! -d build/ui_new/ppm ] || same_tree build/ui_new/ppm build/gn_upstream/ui1/ppm; }
}
run "hooks in: upstream's UI renders (every screen, palette, page, value): the same bytes as without them" ui_renders
tracks() {                                 # the 4-track demo: live recording, the keys, the engine switch
    for g in 0 1; do
        upb hostsim $g -O2 || return 1
        rm -rf "build/gn_upstream/tracks$g" && mkdir -p "build/gn_upstream/tracks$g"
        env TRACKS="build/gn_upstream/tracks$g" "$OUT/up${g}_hostsim" 0 0 1 "build/gn_upstream/tracks$g/render.wav" \
            > "$OUT/up${g}_hostsim.log" 2>&1 || { tail -3 "$OUT/up${g}_hostsim.log"; return 1; }
    done
    same_tree build/gn_upstream/tracks0 build/gn_upstream/tracks1
}
run "hooks in: the 4-track demo (hostsim TRACKS): the same WAVs as without them" tracks

# Easy mode
CLANG="${GN_CLANG:-}"                      # clang for the sanitizers (an ignore list: gn_ubsan_upstream.txt)
for c in clang clang-18 clang-17 clang-16; do
    [ -n "$CLANG" ] && break
    command -v "$c" >/dev/null 2>&1 && CLANG=$c
done
[ -n "$CLANG" ] || { echo "no clang (GN_CLANG): the sanitized tests need it"; CLANG=false; }
GNF="-Ibuild/gen -Ifirmware/src -Itests"
SAN="-fsanitize=address,undefined -fno-sanitize-recover=undefined -fsanitize-ignorelist=tests/gn_ubsan_upstream.txt"
run "Easy: the state machine, every review finding, the keys, knobs, loop, undo, screen, saved (ASan, UBSan)" \
    sh -c "$CLANG -O1 -g -w $SAN $GNF -o '$OUT/gn_easy_test' tests/gn_easy_test.c -lm && '$OUT/gn_easy_test'"
run "UX: Gnomad's own screens, one Easy and Advanced (Home, notes, sounds, SHIFT, status) (ASan, UBSan)" \
    sh -c "$CLANG -O1 -g -w $SAN $GNF -o '$OUT/gn_ux_test' tests/gn_ux_test.c -lm && '$OUT/gn_ux_test'"
run "UX: the same with the Gnomad engines (GN_ENGINES 1: the kit's sixteen pads, the FM page) (ASan, UBSan)" \
    sh -c "$CLANG -O1 -g -w $SAN -DGN_UX_ENGINES=1 $GNF -o '$OUT/gn_ux_eng_test' tests/gn_ux_test.c -lm && '$OUT/gn_ux_eng_test'"
run "UX: the retired engines' slots with the editor switch on (GN_EDITOR_HIDES_GONE 1: INFO and DESC \"\", NAMES 0) (ASan, UBSan)" \
    sh -c "$CLANG -O1 -g -w $SAN -DGN_UX_ENGINES=1 -DGN_EDITOR_HIDES_GONE=1 $GNF -o '$OUT/gn_ux_hide_test' tests/gn_ux_test.c -lm && '$OUT/gn_ux_hide_test' UX-7"
run "Easy: upstream's sources leave the mode byte alone (favourites' row 15 byte 30; NENGINES below 15)" \
    python3 tests/gn_mode_byte_test.py firmware/src
run "Easy: the start (pick 1): the first power-on Easy + GNOMAD, the mode kept across power cycles, 1.0.1 accepts our record (ASan, UBSan)" \
    sh -c "$CLANG -O1 -g -w $SAN $GNF -o '$OUT/gn_start_test' tests/gn_start_test.c -lm && '$OUT/gn_start_test'"
run "Easy: every screen in every state drawn whole: no undefined behaviour (UBSan), the canvas's last 6,328 B untouched" \
    sh -c "$CLANG -O1 -g -w -fsanitize=undefined -fno-sanitize-recover=undefined $GNF -o '$OUT/gn_draw_test' tests/gn_draw_test.c -lm && '$OUT/gn_draw_test'"
run "Easy: the stack on the host, Felucca's walk against Easy's (painted thread stacks; the target's: gn_budget.py)" \
    sh -c "$CC -O2 -w $GNF -o '$OUT/gn_stack_test' tests/gn_stack_test.c -lm -lpthread && '$OUT/gn_stack_test'"
mkdir -p build/gn_sounds
run "Easy: the eight sounds and the drums: each speaks at once, each knob a clear change (WAVs in build/gn_sounds)" \
    sh -c "$CC -O2 -w $GNF -o '$OUT/gn_sound_test' tests/gn_sound_test.c -lm && '$OUT/gn_sound_test' build/gn_sounds"
rm -rf build/gn_screens
run "Easy: the screens without a synth (build/gn_screens), each the same bytes as tests/gn_screens" \
    sh -c "$CC -O1 -w $GNF -o '$OUT/gn_screen' tests/gn_screen.c -lm && '$OUT/gn_screen' build/gn_screens tests/gn_screens"
rm -rf build/gn_screens_eng
run "UX: the same screens with the Gnomad engines, and the FM page (build/gn_screens_eng; no approved copy)" \
    sh -c "$CC -O1 -w -DGN_UX_ENGINES=1 $GNF -o '$OUT/gn_screen_eng' tests/gn_screen.c -lm && '$OUT/gn_screen_eng' build/gn_screens_eng"

# Gnomad engines (FORK.md): the sound core through the firmware's audio path, the swap on (GN_ENGINES 1)
run "Gnomad engines: the slots, the core's boot, each engine sounds and frees its voices, switch, mix, controls, idle" \
    sh -c "$CC -O2 -w $GNF -o '$OUT/gn_core_test' tests/gn_core_test.c -lm && '$OUT/gn_core_test'"
run "Gnomad engines: the presets are the banks': census, NAMES, PRESET bytes, the whole bank bound, every kit's 16 pads, Easy by bank name, its table for the app in build/gn_easy_table.tsv (ASan, UBSan)" \
    sh -c "$CLANG -O1 -g -w $SAN -DGN_BANK_OFF $GNF -o '$OUT/gn_bank_test_off' tests/gn_bank_test.c -lm && '$OUT/gn_bank_test_off' '$OUT/gn_easy_off.tsv' && $CLANG -O1 -g -w $SAN $GNF -o '$OUT/gn_bank_test' tests/gn_bank_test.c -lm && '$OUT/gn_bank_test' '$OUT/gn_easy_off.tsv' build/gn_easy_table.tsv"
run "Gnomad engines: at most 127 presets an engine (a synthetic FM bank of 200): NAMES whole names in its buffer, PRESET, the screens' list (ASan, UBSan)" \
    sh -c "$CLANG -O1 -g -w $SAN -DGN_BANK_SYNTH $GNF -o '$OUT/gn_bank_test_synth' tests/gn_bank_test.c -lm && '$OUT/gn_bank_test_synth'"
run "Gnomad engines (round EW): the Advanced pages on the core: every page knob moves its engine's sound or says why not, the effects pages, rest, kits' pads, the Gnome's syllables, no pan (build/gn_wire.tsv) (ASan, UBSan)" \
    sh -c "$CLANG -O1 -g -w $SAN $GNF -o '$OUT/gn_wire_test' tests/gn_wire_test.c -lm && '$OUT/gn_wire_test'"
run "Gnomad engines: the vendored core is the commit CORE-VERSION.txt names, byte for byte (SHA-256)" \
    python3 tests/gn_core_vendor_test.py
run "Gnomad engines: the vendored content is what CONTENT-VERSION.txt names, its header regenerated byte for byte" \
    python3 tests/gn_content_test.py
run "Gnomad engines: the budget gate's own test, and the CONTENT line against the vendored content" \
    python3 tests/gn_budget_test.py
run "Gnomad engines: the target cost check skips only what the build's configuration compiled out" \
    python3 tests/gn_target_budget_test.py
run "Gnomad engines: the target cost gate (the reachable scorer's control tick both ways round, the adopted lines)" \
    python3 tests/gn_slot_cost_test.py

[ $fail -eq 0 ] && echo "ALL FORK TESTS PASSED" || { echo "FORK TESTS FAILED"; exit 1; }
