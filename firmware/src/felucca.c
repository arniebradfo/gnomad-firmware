/* Gnomad (FORK.md, Branding round V1.6): the app's USB manufacturer string is "Gnomad". usb.c writes STR1 once,
 * above its #ifdef FELUCCA_LOADER, for the update loader and the app alike, and get_desc sends STR1. Here (the app
 * only): STR1 -> GN_STR1 is saved, and upstream's array is renamed (unused, dropped by the linker); usb.c's approved
 * line in the app's branch pops the saved name and defines GN_STR1 "Gnomad", so get_desc sends that
 * (.github/ci/gn_protected.py). loader.c, upstream's host tests and anything else that includes usb.c without these
 * lines: nothing to pop, STR1 stays upstream's, every byte. */
#define STR1 GN_STR1
#pragma push_macro("STR1")
#undef STR1
#define STR1 __attribute__((unused)) STR1_UPSTREAM
#include "usb.c"
typedef char gn_usb_manufacturer_ok[sizeof STR1 == 14 ? 1 : -1];   /* get_desc's STR1: GN_STR1, "Gnomad" (14 B) */
#undef STR1
