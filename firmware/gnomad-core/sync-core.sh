# Gnomad (FORK.md, "Gnomad engines"): vendor (or re-vendor) the Gnomad sound core into firmware/gnomad-core.
#
#   firmware/gnomad-core/sync-core.sh [REF]          REF: a commit, tag or branch of the core (default: main)
#   GNOMAD_CORE=/path/to/gnomad-core                 the core's repository (default: ~/dev/gnomad-core)
#   SKIP_CORE_TESTS=1                                do not run the core's own `make test` at REF
#
# One command, nothing else to edit: it exports REF with `git archive` (committed bytes only, never the core's
# working tree), runs the core's own table generator, and writes here
#   include/gnomad_core.h         the public header, as committed
#   src/*.c, src/*.h              the core's sources, as committed (the Makefile's SRC list, in its order), plus
#     src/tables.h                the generated tables, each table under its own guard (unity_tables.py): the
#                                 firmware is one translation unit (gn_core.c includes the core), the per-file blocks are not
#     src/gnomad_core.h           a one-line forward to ../include/gnomad_core.h (the core's sources include it by
#                                 name; the firmware's include paths, tools/build.py's, are fixed)
#   third_party/<lib>/            open-source code the core adapts: the files at the library's top
#                                 (LICENSE, NOTICE, UPSTREAM.md, CHANGES.md) and its adapted/ sources, as committed
#                                 (the core's sources include them by relative path); upstream/ (the core's host-test
#                                 reference) is not vendored: nothing in the firmware builds it
#   CORE-NOTICE                   the core's NOTICE, as committed (the adapted code's copyright and permission notices)
#   gn_core_unity.h               the core as one unit: every GC_TABLES_DEFINE_*, the sources, then #undef of
#                                 every macro the sources define (none leaks into the firmware after them)
#   gn_core_records.h             the patches, kit and SAMPLE asset the firmware binds (gen_records.c, checked
#                                 against the core: valid records, every engine sounds and frees its voices)
#   CORE-VERSION.txt              the commit, what was checked, the files and their SHA-256
# then prints `git status` of this folder. Commit the result ("engines: re-vendor gnomad-core <sha>").
set -eu
here=$(cd "$(dirname "$0")" && pwd)
repo=${GNOMAD_CORE:-$HOME/dev/gnomad-core}
ref=${1:-main}
sha=$(git -C "$repo" rev-parse --verify "$ref^{commit}")
subject=$(git -C "$repo" log -1 --format=%s "$sha")
cdate=$(git -C "$repo" log -1 --format=%cI "$sha")
tree=$(git -C "$repo" rev-parse "$sha^{tree}")
tmp=$(mktemp -d "${TMPDIR:-/tmp}/gn-core.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
mkdir "$tmp/core"
git -C "$repo" archive "$sha" | tar -x -C "$tmp/core"
cd "$tmp/core"
tp=$(find third_party -path '*/upstream' -prune -o -type f -print 2>/dev/null | grep -E '^third_party/[^/]+/([^/]+|adapted/[^/]+)$' | sort || true)
srcs=$(sed -n '/^SRC *:=/,/^$/p' Makefile | tr -d '\\' | tr ' \t' '\n\n' | grep '^src/.*\.c$')
[ -n "$srcs" ] || { echo "sync-core.sh: no SRC list in the core's Makefile at $sha" >&2; exit 1; }
gen=tools/gen_tables.py
[ -f "$gen" ] || gen=scripts/gen_tables.py
python3 -I "$gen" >/dev/null
tests="not run (SKIP_CORE_TESTS=1)"
if [ -z "${SKIP_CORE_TESTS:-}" ]; then
    make test >"$tmp/test.log" 2>&1 || { tail -20 "$tmp/test.log"; echo "sync-core.sh: the core's make test fails at $sha" >&2; exit 1; }
    tests=$(grep -E '^[0-9]+ passed' "$tmp/test.log" | tail -1)
    python3 -I "$gen" >/dev/null
fi
# the records, against the core as committed (its own tables, before the unity guards)
cc -std=c99 -O1 -w -Iinclude -Isrc -o "$tmp/gen_records" "$here/gen_records.c" $srcs
"$tmp/gen_records" "$tmp/gn_core_records.h" >"$tmp/records.txt"
python3 -I "$here/unity_tables.py" src/tables.h "$tmp/tables.h" >"$tmp/unity.txt"

# replace the vendored copy
rm -rf "$here/include" "$here/src" "$here/third_party" "$here/CORE-NOTICE"
mkdir -p "$here/include" "$here/src"
cp include/gnomad_core.h "$here/include/"
for f in $srcs; do cp "$f" "$here/src/"; done
for f in src/*.h; do [ "$f" = src/tables.h ] || cp "$f" "$here/src/"; done
cp "$tmp/tables.h" "$here/src/tables.h"
for f in $tp; do mkdir -p "$here/$(dirname "$f")"; cp "$f" "$here/$f"; done
[ ! -f NOTICE ] || cp NOTICE "$here/CORE-NOTICE"
printf '/* firmware/gnomad-core/sync-core.sh: the core sources include their public header by name */\n#include "../include/gnomad_core.h"\n' \
    >"$here/src/gnomad_core.h"
cp "$tmp/gn_core_records.h" "$here/gn_core_records.h"
{
    echo "/* SPDX-License-Identifier: GPL-3.0-only"
    echo " * Generated by firmware/gnomad-core/sync-core.sh from gnomad-core $sha: do not edit."
    echo " * The core's sources as one unit for the firmware's single translation unit (included by firmware/src/gn_core.c). */"
    echo "#ifdef GC_DRUM_LAB"
    echo "#error \"GC_DRUM_LAB is the core's lab-only drum build (division in the render path): never in the firmware\""
    echo "#endif"
    grep -o '^#ifdef GC_TABLES_DEFINE_[A-Z0-9_]*' src/tables.h | sed 's/#ifdef /#define /' | sort -u
    for f in $srcs; do echo "#include \"$f\""; done
    python3 -I -c 'import re, sys
names = set()
for f in sys.argv[1:]:
    names |= set(re.findall(r"^[ \t]*#[ \t]*define[ \t]+([A-Za-z_][A-Za-z0-9_]*)", open(f).read(), re.M))
print("".join("#undef %s\n" % n for n in sorted(names - {"GNOMAD_CORE_H"})), end="")' $srcs src/*.h \
        $(printf '%s\n' $tp | grep '\.h$' || true)
} >"$here/gn_core_unity.h"
{
    echo "gnomad-core vendored into the Gnomad firmware (FORK.md, \"Gnomad engines\")"
    echo
    echo "commit   $sha"
    echo "subject  $subject"
    echo "date     $cdate"
    echo "tree     $tree"
    echo "source   gnomad-core (git archive of the commit: committed bytes only; GNOMAD_CORE names the local clone)"
    echo "vendored by firmware/gnomad-core/sync-core.sh: every field here comes from the commit, so a re-run at the"
    echo "         same commit writes the same bytes (no time, no local path)"
    echo "tests    the core's make test at this commit: $tests"
    echo
    echo "Licence: the core is the owner's (Kyle Palaniuk) code, clean-room per the core's PROVENANCE.md; inside this"
    echo "firmware it is granted under GPL-3.0-only as part of the firmware's corresponding source (PROVENANCE.md rule 5)."
    echo "The files are vendored as committed, without SPDX headers of their own; NOTICE.txt here states the grant."
    if [ -n "$tp" ] || [ -f NOTICE ]; then
    echo "Open-source code the core adapts keeps its own licence and notices: CORE-NOTICE (the core's"
    echo "NOTICE, as committed) and third_party/<lib>/ (LICENSE, NOTICE, UPSTREAM.md, CHANGES.md)."
    fi
    echo
    echo "Changes against the commit: src/tables.h is the core's generated tables.h with each table under its own"
    echo "guard ($(cat "$tmp/unity.txt")); src/gnomad_core.h is a generated forward; gn_core_unity.h and"
    echo "gn_core_records.h are generated. Not vendored: third_party/*/upstream (the core's host-test reference, built"
    echo "by no firmware target). Nothing else differs."
    echo
    cat "$tmp/records.txt"
    echo
    echo "files (SHA-256):"
    (cd "$here" && shasum -a 256 include/* src/* $tp $( [ ! -f CORE-NOTICE ] || echo CORE-NOTICE ) gn_core_unity.h gn_core_records.h | sed 's/^/  /')
} >"$here/CORE-VERSION.txt"
echo "sync-core.sh: gnomad-core ${sha%"${sha#???????}"} ($subject) -> $here"
git -C "$here" status --short -- . || true
