// Gnomad Drums: the drum models of the eurorack "peaks/drums" code above
// (BassDrum, SnareDrum, HighHat; FmDrum as a recipe) adapted to C99 fixed
// point for the Gnomad sound core. Changes are listed in src/drum_blocks.h,
